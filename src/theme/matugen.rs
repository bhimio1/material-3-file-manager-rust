pub fn config_dir() -> Option<PathBuf> {
    dirs::config_dir().map(|d| d.join("material_3_file_manager"))
}

/// The file matugen writes and we watch for live theme changes.
pub fn theme_json_path() -> Option<PathBuf> {
    config_dir().map(|d| d.join("theme.json"))
}

/// Colors generated by end-4's illogical-impulse / end4-pC shell on every
/// wallpaper or scheme change. Same role names as our `theme.json`.
pub fn end4_colors_path() -> Option<PathBuf> {
    dirs::state_dir().map(|d| d.join("quickshell/user/generated/colors.json"))
}

/// The palette file in use: the end-4 shell's colors when present, so the
/// file manager always matches the shell, else our own matugen output.
pub fn palette_path() -> Option<PathBuf> {
    [end4_colors_path(), theme_json_path()]
        .into_iter()
        .flatten()
        .find(|p| p.is_file())
}

pub fn template_path() -> Option<PathBuf> {
    config_dir().map(|d| d.join("matugen_template.json"))
}

/// Snippet for `~/.config/matugen/config.toml`.
pub fn config_snippet() -> String {
    let template = template_path().unwrap_or_default();
    let output = theme_json_path().unwrap_or_default();
    format!(
        "[templates.m3fm]\ninput_path = \"{}\"\noutput_path = \"{}\"\n",
        template.display(),
        output.display()
    )
}

pub fn write_template() -> anyhow::Result<PathBuf> {
    let path = template_path().ok_or_else(|| anyhow::anyhow!("no config directory"))?;
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(&path, TEMPLATE)?;
    Ok(path)
}
